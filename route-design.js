function routeTextPoints(text) {
  const normalized = text.trim().toUpperCase().normalize("NFD").replace(/\p{M}/gu, "").replace(/\s+/g, " ");
  if (!/^[A-Z0-9][A-Z0-9 ]{0,15}$/.test(normalized)) return [];
  const points = [];
  let offset = 0;
  for (const character of normalized) {
    if (character !== " ") {
      for (const pair of ROUTE_LETTERS[character].split(" ")) {
        points.push([offset + Number(pair[0]), Number(pair[1])]);
      }
    }
    offset += character === " " ? 3 : 6;
  }
  return points;
}

